import test from 'node:test';
import assert from 'node:assert/strict';
import { applyMigrations } from '../src/db/migrate.js';
import {PGlite} from '@electric-sql/pglite';
import {createPostgresStore} from '../src/db/postgres.js';
import {createReviewedDraft} from '../src/advisor.js';
test('V4 PostgreSQL engine: draft/edit/regenerate/reconnect/history/duplicate/opt-out with additive Gemini migration',async()=>{
 const db=new PGlite();
 const query=async(sql,args)=>{
  const result=args?.length?await db.query(sql,args):(await db.exec(sql)).at(-1);
  return {...result,rowCount:result.rows.length || result.affectedRows || 0};
 };
 const pool={query,connect:async()=>({query,release(){}}),end:async()=>{}};
 const migration='20261109190000_conversation_archive.sql';
 assert.ok((await applyMigrations(pool)).some(item=>item.filename===migration&&item.status==='applied'));
 assert.ok((await applyMigrations(pool)).every(item=>item.status==='already-applied'));
 await db.exec('SET search_path TO gsw_sdr');
 const s=await createPostgresStore('test',{pool});const phone='000000040002';
 try{
 assert.equal((await s.ingest({phone,id:'sql-1',text:'Quero um site',manual:true})).accepted,true);
 const a=await createReviewedDraft(s,phone,{manual:true,geminiApiKey:''});assert.equal(a.created,true);assert.equal(a.draft.generationMeta.errorCode,'missing_key');assert.equal((await s.get(phone)).mode,'HUMAN');
 const edit=await s.editDraft(phone,a.draft.id,{text:'Edição preservada',expectedVersion:a.draft.conversationVersion});assert.equal(edit.updated,true);
 const b=await createReviewedDraft(s,phone,{manual:true,regenerate:true,geminiApiKey:'fake'},async()=>({ok:true,json:async()=>({candidates:[{finishReason:'STOP',content:{parts:[{text:'Sugestão Gemini simulada para teste SQL.'}]}}]})}));assert.equal(b.created,true);
 const restarted=await createPostgresStore('test',{pool});const c=await restarted.get(phone);assert.equal(c.messages.length,1);assert.ok(c.drafts.some(d=>d.provider==='gemini'&&d.generationMeta.status==='success'));assert.equal(c.drafts.length,3);assert.ok(c.drafts.some(d=>d.text==='Edição preservada'));
 assert.equal((await s.editDraft(phone,edit.draft.id,{text:'Obsoleta',expectedVersion:edit.draft.conversationVersion})).updated,false);
 assert.equal((await s.ingest({phone,id:'sql-2',text:'Quero um site',manual:true})).reason,'duplicate_text');
 assert.equal((await s.ingest({phone,id:'sql-2',text:'Quero um site',manual:true,allowRepeat:true})).accepted,true);
 assert.equal((await s.ingest({phone,id:'sql-3',text:'Não tenho interesse',manual:true})).accepted,true);assert.equal((await s.get(phone)).optedOut,true);
 assert.equal((await createReviewedDraft(s,phone,{manual:true,geminiApiKey:''})).created,false);
 await s.setContext(phone,{company:'Empresa Fictícia'});
 const archive=await s.setArchived(phone,true);
 assert.ok(archive.archivedAt);
 assert.equal((await s.setArchived(phone,true)).archivedAt.toISOString(),archive.archivedAt.toISOString());
 assert.deepEqual(await s.list(),[]);
 assert.equal((await restarted.list({archived:true,search:'fictícia'}))[0].id,phone);
 assert.equal((await restarted.list({archived:true,search:'40002'}))[0].id,phone);
 assert.equal(await s.setArchived('000000000000',true),null);
 assert.equal((await s.setArchived(phone,false)).archivedAt,null);
 const restored=await restarted.get(phone);
 assert.equal(restored.optedOut,true);
 assert.equal(restored.messages.length,3);
 assert.equal(restored.drafts.length,3);
 assert.equal((await s.list())[0].id,phone);
 const openingPhone='000000040003';
 const initial=await createReviewedDraft(s,openingPhone,{manual:true,opening:true,geminiApiKey:''});
 assert.equal(initial.draft.sourceMessageId,null);
 assert.equal((await s.get(openingPhone)).messages.length,0);
 const unchanged=await s.editDraft(openingPhone,initial.draft.id,{text:initial.draft.text,expectedVersion:initial.draft.conversationVersion});
 assert.equal(unchanged.draft.id,initial.draft.id);assert.equal(unchanged.unchanged,true);
 assert.equal((await createReviewedDraft(s,openingPhone,{manual:true,opening:true,regenerate:true,geminiApiKey:''})).draft.id,initial.draft.id);
 assert.equal((await s.get(openingPhone)).drafts.length,1);
 const changed=await s.editDraft(openingPhone,initial.draft.id,{text:'Abertura revisada pelo SDR.',expectedVersion:initial.draft.conversationVersion});
 assert.equal(changed.updated,true);
 assert.equal((await s.recordFeedback(openingPhone,initial.draft.id,'boa')).recorded,true);
 await s.recordFeedback(openingPhone,initial.draft.id,'boa');
 assert.equal((await db.query("SELECT count(*)::int AS n FROM audit_events WHERE event_type='DRAFT_FEEDBACK'")).rows[0].n,1);
 assert.equal((await s.get(openingPhone)).drafts.length,2);
 assert.equal((await restarted.get(openingPhone)).feedback[0].category,'boa');
 await s.erase(openingPhone);
 await s.erase(phone);assert.equal((await s.list()).length,0);
 }finally{await db.close()}
});
